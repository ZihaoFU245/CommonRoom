-- PostgreSQL representation of SQLite HEAD v19. JSON stays text to preserve
-- serialized payloads and no-op comparisons across an offline transfer.
CREATE TABLE chat_schema(id BIGINT PRIMARY KEY CHECK(id=1), version BIGINT NOT NULL);
INSERT INTO chat_schema VALUES(1,19);
CREATE TABLE state(id BIGINT PRIMARY KEY CHECK(id=1), json TEXT NOT NULL);
CREATE TABLE read_positions(username TEXT NOT NULL, conversation TEXT NOT NULL, sequence BIGINT NOT NULL, PRIMARY KEY(username,conversation));
CREATE INDEX read_positions_conversation ON read_positions(conversation);
CREATE TABLE entities(kind TEXT NOT NULL, key TEXT NOT NULL, json TEXT NOT NULL, projection JSONB NOT NULL, revision BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(kind,key));
CREATE TABLE messages(conversation TEXT NOT NULL, sequence BIGINT NOT NULL, json TEXT NOT NULL, projection JSONB NOT NULL, PRIMARY KEY(conversation,sequence));
CREATE TABLE reactions(conversation TEXT NOT NULL, sequence BIGINT NOT NULL, reaction TEXT NOT NULL, username TEXT NOT NULL,
 PRIMARY KEY(conversation,sequence,reaction,username), FOREIGN KEY(conversation,sequence) REFERENCES messages(conversation,sequence) ON DELETE CASCADE);
CREATE TABLE counters(id BIGINT PRIMARY KEY CHECK(id=1), sequence BIGINT NOT NULL);
CREATE TABLE bot_receipts(account_id TEXT NOT NULL, key TEXT NOT NULL, digest TEXT NOT NULL, conversation TEXT NOT NULL, sequence BIGINT NOT NULL, created BIGINT NOT NULL, PRIMARY KEY(account_id,key));
CREATE INDEX bot_receipts_created ON bot_receipts(created);
CREATE TABLE bot_command_receipts(account_id TEXT NOT NULL, key TEXT NOT NULL, digest TEXT NOT NULL, created BIGINT NOT NULL, outcome TEXT NOT NULL, PRIMARY KEY(account_id,key));
CREATE INDEX bot_command_receipts_created ON bot_command_receipts(created);
CREATE TABLE audit_entries(sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entry_id TEXT NOT NULL UNIQUE, json TEXT NOT NULL);
CREATE TABLE auth_events(sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at BIGINT NOT NULL, client TEXT, username TEXT, outcome TEXT NOT NULL CHECK(outcome IN ('success','failure','logout')));
CREATE INDEX messages_id ON messages((projection #>> '{id}'),conversation);
CREATE INDEX messages_author ON messages(conversation,(projection #>> '{from}'),sequence);
CREATE INDEX messages_time ON messages(conversation,(((projection #>> '{time}'))::bigint));
CREATE INDEX messages_sequence ON messages(sequence);
CREATE INDEX messages_reply ON messages(conversation,(projection #>> '{reply,id}'));
CREATE INDEX entities_id ON entities((projection #>> '{id}')) WHERE kind IN ('room','private');
CREATE TABLE message_accounts(name TEXT NOT NULL, conversation TEXT NOT NULL, sequence BIGINT NOT NULL,
 PRIMARY KEY(name,sequence,conversation), FOREIGN KEY(conversation,sequence) REFERENCES messages(conversation,sequence) ON DELETE CASCADE ON UPDATE CASCADE);
CREATE INDEX message_accounts_message ON message_accounts(conversation,sequence);
CREATE INDEX reactions_username ON reactions(username,conversation);
CREATE FUNCTION chat_message_accounts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  DELETE FROM message_accounts WHERE conversation=OLD.conversation AND sequence=OLD.sequence;
 END IF;
 INSERT INTO message_accounts(name,conversation,sequence)
 SELECT value,NEW.conversation,NEW.sequence FROM (
  SELECT NEW.projection #>> '{from}' AS value
  UNION SELECT NEW.projection #>> '{to}'
  UNION SELECT NEW.projection #>> '{reply,from}'
  UNION SELECT value FROM jsonb_array_elements_text(NEW.projection -> 'mentions')
 ) AS names WHERE value IS NOT NULL ON CONFLICT DO NOTHING;
 RETURN NEW;
END;
$$;
CREATE TRIGGER message_accounts_insert AFTER INSERT ON messages FOR EACH ROW EXECUTE FUNCTION chat_message_accounts();
CREATE TRIGGER message_accounts_update AFTER UPDATE OF json ON messages FOR EACH ROW EXECUTE FUNCTION chat_message_accounts();
CREATE TABLE retention(conversation TEXT PRIMARY KEY, count BIGINT NOT NULL CHECK(count>=0), oldest BIGINT);
CREATE FUNCTION chat_retention() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  INSERT INTO retention VALUES(NEW.conversation,1,NEW.sequence) ON CONFLICT(conversation)
   DO UPDATE SET count=retention.count+1,oldest=least(coalesce(retention.oldest,NEW.sequence),NEW.sequence);
 ELSIF TG_OP='DELETE' THEN
  UPDATE retention SET count=count-1,oldest=(SELECT min(sequence) FROM messages WHERE conversation=OLD.conversation)
   WHERE conversation=OLD.conversation;
  DELETE FROM retention WHERE conversation=OLD.conversation AND count=0;
 ELSE
  DELETE FROM retention WHERE conversation IN (OLD.conversation,NEW.conversation);
  INSERT INTO retention SELECT conversation,count(*),min(sequence) FROM messages
   WHERE conversation IN (OLD.conversation,NEW.conversation) GROUP BY conversation;
 END IF;
 RETURN NULL;
END;
$$;
CREATE TRIGGER retention_insert AFTER INSERT ON messages FOR EACH ROW EXECUTE FUNCTION chat_retention();
CREATE TRIGGER retention_delete AFTER DELETE ON messages FOR EACH ROW EXECUTE FUNCTION chat_retention();
CREATE TRIGGER retention_move AFTER UPDATE OF conversation,sequence ON messages FOR EACH ROW
 WHEN (OLD.conversation!=NEW.conversation OR OLD.sequence!=NEW.sequence) EXECUTE FUNCTION chat_retention();
CREATE TABLE media(id TEXT PRIMARY KEY, uploader TEXT NOT NULL, conversation TEXT NOT NULL, size BIGINT NOT NULL, created BIGINT NOT NULL,
 ready BIGINT NOT NULL, unreferenced BIGINT, staging_clean BIGINT NOT NULL DEFAULT 0, json TEXT NOT NULL, expires BIGINT, published BIGINT,
 deleting BIGINT NOT NULL DEFAULT 0, deleted BIGINT NOT NULL DEFAULT 0, cleanup_attempt BIGINT NOT NULL DEFAULT 0, staging_attempt BIGINT NOT NULL DEFAULT 0);
CREATE TABLE message_media(conversation TEXT NOT NULL, sequence BIGINT NOT NULL, media_id TEXT NOT NULL REFERENCES media(id),
 PRIMARY KEY(conversation,sequence,media_id), FOREIGN KEY(conversation,sequence) REFERENCES messages(conversation,sequence) ON DELETE CASCADE);
CREATE INDEX message_media_id ON message_media(media_id);
CREATE INDEX media_quota ON media(uploader,deleted,published,created,size);
CREATE INDEX media_due_retry ON media(cleanup_attempt,created) WHERE deleted=0 AND deleting=1;
CREATE INDEX media_due_expiry ON media(expires,created) WHERE deleted=0 AND deleting=0;
CREATE INDEX media_due_orphan ON media(unreferenced,created) WHERE deleted=0 AND deleting=0 AND unreferenced IS NOT NULL;
CREATE INDEX media_staging_due ON media(staging_attempt,created) WHERE staging_clean=0;
CREATE INDEX media_tombstone ON media(created) WHERE deleted=1 AND staging_clean=1;
CREATE FUNCTION chat_media_reference_removed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE media SET unreferenced=coalesce(unreferenced,floor(extract(epoch FROM clock_timestamp()))::bigint)
  WHERE id=OLD.media_id AND NOT EXISTS(SELECT 1 FROM message_media WHERE media_id=OLD.media_id);
 RETURN NULL;
END;
$$;
CREATE TRIGGER media_reference_removed AFTER DELETE ON message_media FOR EACH ROW EXECUTE FUNCTION chat_media_reference_removed();
