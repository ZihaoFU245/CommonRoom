/**
 * Assign curated emojis to picker categories using emojibase groups/subgroups.
 * Run after changing src/features/conversation/emojis.ts:
 *   pnpm build:emoji-categories
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const emojisPath = path.join(root, "src/features/conversation/emojis.ts");
const outPath = path.join(root, "src/features/conversation/emojiCategories.ts");

/** @typedef {{ id: string, label: string, icon: string }} CategoryMeta */

/** @type {CategoryMeta[]} */
const CATEGORIES = [
  { id: "faces", label: "Faces", icon: "😀" },
  { id: "gestures", label: "Gestures", icon: "👍" },
  { id: "people", label: "People", icon: "🧑" },
  { id: "nature", label: "Nature", icon: "🌿" },
  { id: "food", label: "Food", icon: "🍔" },
  { id: "places", label: "Places", icon: "🏠" },
  { id: "activities", label: "Activity", icon: "⚽" },
  { id: "objects", label: "Objects", icon: "💡" },
  { id: "symbols", label: "Symbols", icon: "💯" },
  { id: "flags", label: "Flags", icon: "🚩" },
];

const FACE_SUBGROUPS = new Set([
  "face-smiling",
  "face-affection",
  "face-tongue",
  "face-hand",
  "face-neutral-skeptical",
  "face-sleepy",
  "face-unwell",
  "face-hat",
  "face-glasses",
  "face-concerned",
  "face-negative",
  "face-costume",
  "cat-face",
  "monkey-face",
]);

const GESTURE_SUBGROUPS = new Set([
  "hand-fingers-open",
  "hand-fingers-partial",
  "hand-single-finger",
  "hand-fingers-closed",
  "hands",
  "hand-prop",
]);

const PEOPLE_SUBGROUPS = new Set([
  "body-parts",
  "person",
  "person-gesture",
  "person-role",
  "person-fantasy",
  "person-activity",
  "person-sport",
  "person-resting",
  "family",
  "person-symbol",
]);

function stripVs(value) {
  return value.replace(/\uFE0F/g, "");
}

function parseEmojis(source) {
  const match = source.match(/export const EMOJIS = \[([\s\S]*?)\];/);
  if (!match) throw new Error("Could not find EMOJIS export");
  return [...match[1].matchAll(/"((?:\\.|[^"\\])*)"/g)].map((item) =>
    JSON.parse(`"${item[1]}"`),
  );
}

/**
 * @param {number | undefined} group
 * @param {string | undefined} subgroup
 */
function categoryIdFor(group, subgroup) {
  if (group === 0) {
    if (subgroup && FACE_SUBGROUPS.has(subgroup)) return "faces";
    return "symbols";
  }
  if (group === 1) {
    if (subgroup && GESTURE_SUBGROUPS.has(subgroup)) return "gestures";
    if (subgroup && PEOPLE_SUBGROUPS.has(subgroup)) return "people";
    return "people";
  }
  if (group === 3) return "nature";
  if (group === 4) return "food";
  if (group === 5) return "places";
  if (group === 6) return "activities";
  if (group === 7) return "objects";
  if (group === 8) return "symbols";
  if (group === 9) return "flags";
  return "objects";
}

const emojis = parseEmojis(fs.readFileSync(emojisPath, "utf8"));
const data = require("emojibase-data/en/data.json");
const meta = require("emojibase-data/meta/groups.json");
const byEmoji = new Map(data.map((entry) => [stripVs(entry.emoji), entry]));

/** @type {Record<string, string[]>} */
const buckets = Object.fromEntries(CATEGORIES.map((item) => [item.id, []]));

for (const emoji of emojis) {
  const entry = byEmoji.get(stripVs(emoji));
  const subgroup =
    entry?.subgroup === undefined
      ? undefined
      : meta.subgroups[String(entry.subgroup)];
  const id = categoryIdFor(entry?.group, subgroup);
  buckets[id].push(emoji);
}

const categories = CATEGORIES.map((item) => ({
  ...item,
  emojis: buckets[item.id],
}));

const empty = categories.filter((item) => item.emojis.length === 0);
if (empty.length) {
  throw new Error(
    `Empty emoji categories: ${empty.map((item) => item.id).join(", ")}`,
  );
}

const assigned = categories.reduce((sum, item) => sum + item.emojis.length, 0);
if (assigned !== emojis.length) {
  throw new Error(`Category coverage ${assigned} !== curated ${emojis.length}`);
}

const banner =
  "/* Generated by scripts/build-emoji-categories.mjs — do not edit by hand. */\n";
const body =
  banner +
  "export type EmojiCategoryId =\n" +
  CATEGORIES.map((item) => `  | "${item.id}"`).join("\n") +
  ";\n\n" +
  "export interface EmojiCategory {\n" +
  "  id: EmojiCategoryId;\n" +
  "  label: string;\n" +
  "  icon: string;\n" +
  "  emojis: readonly string[];\n" +
  "}\n\n" +
  "/** Curated emoji glyphs grouped like common messenger pickers. */\n" +
  `export const EMOJI_CATEGORIES: readonly EmojiCategory[] = ${JSON.stringify(
    categories,
    null,
    2,
  )};\n\n` +
  "export const DEFAULT_EMOJI_CATEGORY: EmojiCategoryId =\n" +
  `  "${CATEGORIES[0].id}";\n`;

fs.writeFileSync(outPath, body);
console.log(
  `Wrote ${categories.length} categories (${assigned} emojis) to ${path.relative(root, outPath)}`,
);
for (const item of categories) {
  console.log(`  ${item.icon} ${item.label}: ${item.emojis.length}`);
}
